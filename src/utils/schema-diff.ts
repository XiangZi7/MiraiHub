import { i18n } from '@/i18n'
import * as database from '@/api/database'
import type {
  DatabaseColumn,
  DatabaseKind,
  DatabaseTableDetail,
} from '@/types/database'

/** ER 图与结构对比一次最多读取的表数量，避免大库卡住界面。 */
export const SCHEMA_TABLE_LIMIT = 120

/**
 * 读取会话当前库下所有表的详情（字段 / 索引 / 外键）。
 * 以 6 路并发拉取；单表失败时明确报错，避免缺失元数据被误判为需要删除的表。
 */
export async function loadSchemaTables(
  sessionId: string,
  onProgress?: (done: number, total: number) => void
): Promise<{ tables: DatabaseTableDetail[]; truncated: boolean }> {
  const objects = (await database.listObjects(sessionId)).filter(
    object => object.kind === 'table'
  )
  const targets = objects.slice(0, SCHEMA_TABLE_LIMIT)
  const tables: DatabaseTableDetail[] = []
  const failures: string[] = []
  let cursor = 0
  let done = 0
  const worker = async () => {
    while (cursor < targets.length) {
      const object = targets[cursor++]!
      try {
        tables.push(
          await database.tableDetail(
            sessionId,
            object.schema,
            object.name,
            'table'
          )
        )
      } catch {
        failures.push(`${object.schema}.${object.name}`)
      }
      onProgress?.(++done, targets.length)
    }
  }
  await Promise.all(Array.from({ length: 6 }, worker))
  if (failures.length)
    throw new Error(
      i18n.global.t('无法读取部分表结构，已停止对比：{tables}', {
        tables: failures.join(', '),
      })
    )
  tables.sort((a, b) => a.name.localeCompare(b.name))
  return { tables, truncated: objects.length > targets.length }
}

export type SchemaDiffKind =
  | 'add-table'
  | 'drop-table'
  | 'add-column'
  | 'drop-column'
  | 'modify-column'
  | 'add-index'
  | 'drop-index'
  | 'modify-index'
  | 'modify-constraint'

export interface SchemaDiffItem {
  kind: SchemaDiffKind
  table: string
  name: string
  /** 人类可读的差异说明，如 `varchar(32) → varchar(64)` */
  detail: string
  /** 让目标库对齐源库的 SQL */
  sql: string
  /** 当前方言不能自动迁移时只显示差异，不允许导出错误 SQL。 */
  unsupported?: string
}

/** 按方言给标识符加引号。 */
function quote(kind: DatabaseKind, name: string): string {
  return kind === 'mysql'
    ? `\`${name.replaceAll('`', '``')}\``
    : `"${name.replaceAll('"', '""')}"`
}

/** 生成字段定义片段：类型、可空、默认值。 */
function columnDefinition(kind: DatabaseKind, column: DatabaseColumn): string {
  const parts = [quote(kind, column.name), column.dataType]
  if (!column.nullable) parts.push('NOT NULL')
  if (column.autoIncrement && kind === 'postgresql')
    parts.push('GENERATED BY DEFAULT AS IDENTITY')
  else if (
    column.defaultValue !== null &&
    (kind === 'mysql' || column.defaultValue !== '')
  )
    parts.push(`DEFAULT ${columnDefault(kind, column)}`)
  if (column.autoIncrement && kind === 'mysql') parts.push('AUTO_INCREMENT')
  if (kind === 'mysql' && column.comment)
    parts.push(
      `COMMENT '${column.comment.replaceAll('\\', '\\\\').replaceAll("'", "''")}'`
    )
  return parts.join(' ')
}

/** MySQL 元数据的字符串默认值不带引号；表达式及数字按其字段类型保留。 */
function columnDefault(kind: DatabaseKind, column: DatabaseColumn): string {
  const value = column.defaultValue ?? ''
  if (kind !== 'mysql') return value
  if (
    /^(current_timestamp|current_date|current_time|localtimestamp|now)(\(\d*\))?$/i.test(
      value
    ) &&
    /date|time/i.test(column.dataType)
  )
    return value
  if (/^\(.*\)$/s.test(value) || /^b'[01]+'$/i.test(value)) return value
  if (
    /^(tinyint|smallint|mediumint|int|integer|bigint|decimal|numeric|float|double|real|bit|bool)/i.test(
      column.dataType
    ) &&
    /^[-+]?\d+(\.\d+)?([eE][-+]?\d+)?$/.test(value)
  )
    return value
  return `'${value.replaceAll('\\', '\\\\').replaceAll("'", "''")}'`
}

/** 字段签名，用于判定是否发生变化。 */
function columnSignature(column: DatabaseColumn): string {
  return JSON.stringify([
    column.dataType.trim(),
    column.nullable,
    column.autoIncrement ? null : column.defaultValue,
    column.autoIncrement,
  ])
}

/**
 * 对比源库与目标库的表结构，返回让“目标”与“源”一致所需的差异与 SQL。
 * 只覆盖表、字段、普通 / 唯一索引；外键、触发器等不在范围内。
 */
export function diffSchemas(
  kind: DatabaseKind,
  source: readonly DatabaseTableDetail[],
  target: readonly DatabaseTableDetail[],
  targetSchema: string
): SchemaDiffItem[] {
  const items: SchemaDiffItem[] = []
  const qualified = (table: string, schema = targetSchema) =>
    kind === 'postgresql' && schema
      ? `${quote(kind, targetSchema || schema)}.${quote(kind, table)}`
      : quote(kind, table)
  const tableKey = (table: DatabaseTableDetail) =>
    kind === 'postgresql'
      ? `${targetSchema || table.schema}\0${table.name}`
      : table.name
  const targetByName = new Map(target.map(table => [tableKey(table), table]))
  const sourceNames = new Set(source.map(tableKey))

  for (const table of source) {
    const other = targetByName.get(tableKey(table))
    const tableName = qualified(table.name, table.schema)
    // 前缀索引需要服务端完整定义，缺少完整元数据时禁止生成错误索引。
    const indexUnsupported = (index: DatabaseTableDetail['indexes'][number]) =>
      index.subPart || index.columns.some(name => !name)
        ? i18n.global.t('特殊索引需要手动迁移')
        : undefined
    const createIndex = (index: DatabaseTableDetail['indexes'][number]) =>
      `CREATE ${index.unique ? 'UNIQUE ' : ''}INDEX ${quote(kind, index.name)} ON ${tableName} (${index.columns.map(name => quote(kind, name)).join(', ')});`
    const dropIndex = (name: string) =>
      kind === 'mysql'
        ? `DROP INDEX ${quote(kind, name)} ON ${tableName};`
        : `DROP INDEX ${kind === 'postgresql' && (targetSchema || table.schema) ? `${quote(kind, targetSchema || table.schema)}.` : ''}${quote(kind, name)};`
    if (!other) {
      const columns = table.columns.map(
        column => `  ${columnDefinition(kind, column)}`
      )
      if (table.primaryKey.length)
        columns.push(
          `  PRIMARY KEY (${table.primaryKey.map(name => quote(kind, name)).join(', ')})`
        )
      items.push({
        kind: 'add-table',
        table: table.name,
        name: table.name,
        detail: `${table.columns.length} columns`,
        sql:
          `CREATE TABLE ${tableName} (\n${columns.join(',\n')}\n);` +
          table.indexes
            .filter(index => !index.primary && !indexUnsupported(index))
            .map(index => `\n${createIndex(index)}`)
            .join(''),
      })
      if (
        table.foreignKeys.length ||
        table.indexes.some(index => !index.primary && indexUnsupported(index))
      )
        items.push({
          kind: 'modify-constraint',
          table: table.name,
          name: table.name,
          detail: '',
          sql: '',
          unsupported: i18n.global.t('外键、主键或特殊表属性变化需要手动迁移'),
        })
      continue
    }
    const otherColumns = new Map(
      other.columns.map(column => [column.name, column])
    )
    const ownColumns = new Set(table.columns.map(column => column.name))
    for (const column of table.columns) {
      const existing = otherColumns.get(column.name)
      if (!existing) {
        items.push({
          kind: 'add-column',
          table: table.name,
          name: column.name,
          detail: column.dataType,
          sql: `ALTER TABLE ${tableName} ADD COLUMN ${columnDefinition(kind, column)};`,
        })
      } else if (columnSignature(existing) !== columnSignature(column)) {
        const statements: string[] = []
        const columnName = quote(kind, column.name)
        let unsupported: string | undefined
        if (kind === 'mysql')
          statements.push(
            `ALTER TABLE ${tableName} MODIFY COLUMN ${columnDefinition(kind, column)};`
          )
        else if (kind === 'sqlite')
          unsupported = i18n.global.t('SQLite 修改字段需要重建表，请手动迁移')
        else {
          if (existing.autoIncrement !== column.autoIncrement)
            unsupported = i18n.global.t('自增方式变化需要手动迁移')
          if (existing.dataType !== column.dataType) {
            if (existing.defaultValue != null)
              statements.push(
                `ALTER TABLE ${tableName} ALTER COLUMN ${columnName} DROP DEFAULT;`
              )
            statements.push(
              `ALTER TABLE ${tableName} ALTER COLUMN ${columnName} TYPE ${column.dataType};`
            )
          }
          if (existing.nullable !== column.nullable)
            statements.push(
              `ALTER TABLE ${tableName} ALTER COLUMN ${columnName} ${column.nullable ? 'DROP' : 'SET'} NOT NULL;`
            )
          if (
            !column.autoIncrement &&
            (existing.defaultValue !== column.defaultValue ||
              existing.dataType !== column.dataType)
          ) {
            statements.push(
              `ALTER TABLE ${tableName} ALTER COLUMN ${columnName} ${column.defaultValue == null || column.defaultValue === '' ? 'DROP DEFAULT' : `SET DEFAULT ${column.defaultValue}`};`
            )
          }
        }
        const sql = unsupported ? '' : statements.join('\n')
        items.push({
          kind: 'modify-column',
          table: table.name,
          name: column.name,
          ...(unsupported ? { unsupported } : {}),
          detail: `${existing.dataType}${existing.nullable ? '' : ' NOT NULL'} → ${column.dataType}${column.nullable ? '' : ' NOT NULL'}`,
          sql,
        })
      }
    }
    for (const column of other.columns)
      if (!ownColumns.has(column.name))
        items.push({
          kind: 'drop-column',
          table: table.name,
          name: column.name,
          detail: column.dataType,
          sql: `ALTER TABLE ${tableName} DROP COLUMN ${quote(kind, column.name)};`,
        })

    const indexKey = (index: DatabaseTableDetail['indexes'][number]) =>
      JSON.stringify([index.columns, index.unique, index.subPart ?? null])
    const otherIndexes = new Map(
      other.indexes
        .filter(index => !index.primary)
        .map(index => [indexKey(index), index])
    )
    const ownIndexes = new Set(
      table.indexes.filter(index => !index.primary).map(indexKey)
    )
    for (const index of table.indexes) {
      if (index.primary || otherIndexes.has(indexKey(index))) continue
      const replacing = other.indexes.find(
        existing => !existing.primary && existing.name === index.name
      )
      const unsupported = indexUnsupported(index)
      items.push({
        kind: replacing ? 'modify-index' : 'add-index',
        table: table.name,
        name: index.name,
        detail: `(${index.columns.join(', ')})${index.unique ? ' UNIQUE' : ''}`,
        sql: unsupported
          ? ''
          : `${replacing ? `${dropIndex(index.name)}\n` : ''}${createIndex(index)}`,
        ...(unsupported ? { unsupported } : {}),
      })
    }
    for (const index of other.indexes) {
      if (
        index.primary ||
        ownIndexes.has(indexKey(index)) ||
        table.indexes.some(own => !own.primary && own.name === index.name)
      )
        continue
      items.push({
        kind: 'drop-index',
        table: table.name,
        name: index.name,
        detail: `(${index.columns.join(', ')})`,
        sql: dropIndex(index.name),
      })
    }
    // 自增计数器随数据变化，比较表属性时排除它；外键跨库引用仍需区分目标库。
    const optionsKey = (options: DatabaseTableDetail['options']) =>
      options
        ? JSON.stringify([
            options.engine,
            options.charset,
            options.collation,
            options.rowFormat,
            options.comment,
          ])
        : ''
    const foreignKey = (owner: DatabaseTableDetail) =>
      owner.foreignKeys
        .map(key => ({
          ...key,
          referencedSchema:
            kind === 'mysql' && key.referencedSchema === owner.schema
              ? ''
              : key.referencedSchema,
        }))
        .sort((a, b) => a.name.localeCompare(b.name))
    if (
      JSON.stringify(table.primaryKey) !== JSON.stringify(other.primaryKey) ||
      JSON.stringify(foreignKey(table)) !== JSON.stringify(foreignKey(other)) ||
      optionsKey(table.options) !== optionsKey(other.options)
    )
      items.push({
        kind: 'modify-constraint',
        table: table.name,
        name: table.name,
        detail: '',
        sql: '',
        unsupported: i18n.global.t('外键、主键或特殊表属性变化需要手动迁移'),
      })
  }

  for (const table of target)
    if (!sourceNames.has(tableKey(table)))
      items.push({
        kind: 'drop-table',
        table: table.name,
        name: table.name,
        detail: `${table.columns.length} columns`,
        sql: `DROP TABLE ${qualified(table.name, table.schema)};`,
      })
  return items.sort(
    (a, b) =>
      (a.kind === 'drop-index' ? -1 : 0) - (b.kind === 'drop-index' ? -1 : 0)
  )
}
